import type { ReactNode } from 'react'

export type ListRowProps = {
  /** Строка или текст с метками папок (PathText): заголовок прошлого разговора. */
  title: ReactNode
  /** Строка под заголовком: состояние, сколько, с какого времени. */
  description?: ReactNode | undefined
  /**
   * Под строкой описания - текст в несколько строк: кусок найденного сообщения, почему модель
   * указала сюда. Не обрезается многоточием, в отличие от описания.
   */
  detail?: ReactNode | undefined
  /** Слева: значок, аватар проекта, отметка. */
  leading?: ReactNode | undefined
  /** Справа: метка состояния. */
  trailing?: ReactNode | undefined
  /**
   * Свои кнопки строки справа, вне нажимаемой части: звезда и удаление прогона, убрать
   * расписание. Кнопка внутри кнопки строки не работала бы - она стоит рядом.
   */
  aside?: ReactNode | undefined
  /** Есть - строка нажимается целиком и ведёт дальше (стрелка справа). */
  onClick?: (() => void) | undefined
  /** Приглушённая: недавний проект, закрытая очередь. */
  muted?: boolean | undefined
}
