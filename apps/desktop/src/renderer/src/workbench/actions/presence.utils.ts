/** Сколько после последнего ввода человек ещё считается в окне: читает код, смотрит ленту. */
export const PRESENCE_IDLE_MS = 3 * 60_000

/** Как часто отмечать минуту, пока человек тут без ввода. */
export const PRESENCE_TICK_MS = 15_000

/** Движение мыши - не чаще раза в секунду: событий бывает по сотне в секунду. */
export const PRESENCE_MOVE_MS = 1_000

/**
 * Идёт ли сейчас минута присутствия: окно в фокусе и ввод был не дольше трёх минут назад.
 * Фокус обязателен - открытое за другими окнами окно не значит, что человек здесь, а ввод
 * обязателен - брошенное в фокусе окно не набирает минут. lastInput 0 - ввода ещё не было.
 */
export const isPresent = (now: number, lastInput: number, focused: boolean): boolean =>
  focused && lastInput > 0 && now - lastInput <= PRESENCE_IDLE_MS
