/**
 * Размеры меток показа Walkthrough (ADR 0134) в точках окна меток - то есть экрана. Толщины -
 * как у маркера на созвоне: видно с другого конца стола, но текст под линией не тонет.
 */

/** Толщина обводки маркером. */
export const CIRCLE_STROKE = 5

/** Зазор обводки от области: шире у крупного, но не меньше и не больше этого. */
export const CIRCLE_PAD_MIN = 8
export const CIRCLE_PAD_MAX = 22

/** Самая маленькая петля: иконку в 12 точек обводят кружком, а не точкой. */
export const CIRCLE_MIN_RADIUS = 18

/**
 * Петля - суперэллипс: у почти квадратной области (иконка) - овал (степень 2), у длинной и плоской
 * (строка, кнопка с подписью) - между овалом и прямоугольником (до степени 3), чтобы не раздуваться
 * в высоту. Полная «квадратность» - у области шире этого во столько раз.
 */
export const CIRCLE_SQUARENESS_MAX = 3
export const CIRCLE_WIDE_ASPECT = 4

/** Точек на петлю: глаз не видит изломов, а путь короткий. */
export const CIRCLE_SAMPLES = 72

/**
 * Рука не замыкает петлю точно: конец заходит за начало на столько радиан и ложится чуть шире
 * (спираль), а радиус чуть дрожит.
 */
export const CIRCLE_OVERSHOOT = 0.45
export const CIRCLE_SPREAD = 0.06
export const CIRCLE_WOBBLE = 0.025

/** Толщина стрелки (у Shotter по умолчанию 3 - на снимке; на живом экране вдвое). */
export const ARROW_STROKE = 6

/** Изгиб стрелки поперёк линии (доля её длины), как рисует рука; 0 - прямая. */
export const ARROW_BEND = 0.18

/** Точек на кривую стрелки (как у Shotter). */
export const ARROW_SAMPLES = 48

/** Зазор и скругление выреза затемнения вокруг области. */
export const SPOTLIGHT_PAD = 12
export const SPOTLIGHT_RADIUS = 12
