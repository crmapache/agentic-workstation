/**
 * Вкладки середины окна одного проекта. Ключ вкладки - путь файла (от корня проекта, а у
 * файла вне проекта, открытого ссылкой, - абсолютный), ключ вкладки разницы (diffTabKey) или
 * истории (historyTabKey). keys - в порядке открытия, он же порядок на полосе: первая в нём - самая
 * давняя, её и закрывает переполнение. recent - те же ключи в порядке выбора,
 * последний - активный: закрыл активную - открылась та, что была до неё.
 */
export type EditorTabs = {
  keys: string[]
  recent: string[]
}

/**
 * Что показывает вкладка: файл в редакторе, его разницу с последним коммитом, как «Commit:
 * файл» в WebStorm, или локальную историю файла или папки (ADR 0045; '' - весь проект). Путь
 * - от корня проекта; у файла вне проекта - абсолютный (ни разницы, ни истории у него нет:
 * проект его не знает).
 */
export type TabTarget = { kind: 'file' | 'diff' | 'history'; path: string }
