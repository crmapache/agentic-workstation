import type { FileEdit } from './change-revert'

/**
 * Файл хода глазами отката: точные правки по порядку и что про них известно. Собирает его
 * драйвер провайдера из своего потока, сверяет и откатывает ядро.
 */
export type TurnFile = {
  path: string
  edits: FileEdit[]
  /** Хоть одна правка пришла без диффа: что ход сделал с файлом, знает только копия провайдера. */
  owing: boolean
  /** Ни одна правка ничего не поменяла (запись того же текста). */
  unchanged: boolean
}
