import { DAY_MS, HOUR_MS, MINUTE_MS, SECOND_MS } from '@shared/time-units'

/** Файл базы в userData. */
export const STATS_DB_FILE = 'statistics.sqlite'

/**
 * Промежуток между записями журнала длиннее этого - не работа агента: человек ушёл,
 * а разговор лежал. Так оценка времени не тянет хода через обед.
 */
export const IDLE_GAP_MS = 15 * MINUTE_MS

/** Пауза присутствия длиннее этой делит рабочие сессии человека. */
export const WORK_SESSION_GAP_MINUTES = 30

/** Как часто дочитывать журналы провайдеров в фоне. */
export const SCAN_INTERVAL_MS = MINUTE_MS

/** Окно узнаёт об изменениях не чаще этого: перерисовка графиков не бесплатна. */
export const CHANGED_THROTTLE_MS = 30 * SECOND_MS

/**
 * Шаг сложения в SQL - четверть часа. Пояса со сдвигом в полчаса и 45 минут кратны ему,
 * так что местные часы и дни собираются из шагов без ошибки на границе.
 */
export const SLOT_MS = 15 * MINUTE_MS

/**
 * Период не длиннее этого рисуется по часам, длиннее - по дням: неделя по часам показывает
 * ритм суток, 30 дней по часам - уже штриховка. Час запаса - неделя с переводом часов назад
 * длиннее на час и иначе ушла бы в дни.
 */
export const HOURLY_PERIOD_MAX_MS = 7 * DAY_MS + HOUR_MS

/** Календарь активности - год, как у GitHub. */
export const CALENDAR_WEEKS = 53

/** Сколько строк в «частых»: инструменты, серверы, сценарии, языки. */
export const TOP_ROWS = 10

/** Длина окна пика: три дня недели и три часа. */
export const PEAK_SPAN = 3

/** Сколько байт журнала читать за раз. */
export const READ_CHUNK_BYTES = 1 << 20

/**
 * После стольких байт прочитанного строки пишутся в базу одной транзакцией вместе со
 * смещением файла: транзакция короткая, а оборванный проход продолжится с того же места.
 */
export const FLUSH_BYTES = 8 << 20

/**
 * Сколько сообщений базы OpenCode читать за раз: сообщение с вызовами - десятки килобайт JSON,
 * страница держит память потока в пределах нескольких мегабайт.
 */
export const OPENCODE_PAGE_ROWS = 200

/**
 * Запас назад при дочитывании базы OpenCode: правка сообщения в ту же миллисекунду, что
 * последняя прочитанная, иначе осталась бы за отметкой. Перечитанное пишется повторно без
 * вреда - ключи записей те же.
 */
export const OPENCODE_REREAD_MS = 5 * SECOND_MS
