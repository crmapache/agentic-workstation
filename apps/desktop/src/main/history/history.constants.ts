import { DAY_MS, HOUR_MS, MINUTE_MS, SECOND_MS } from '@shared/time-units'

/** Папка истории в userData: база SQLite с событиями и содержимым версий. */
export const HISTORY_DIR_NAME = 'local-history'

export const HISTORY_DB_NAME = 'history.db'

/** Сколько дней живёт событие истории, как в WebStorm по умолчанию - месяц. */
export const RETENTION_DAYS = 30

export const RETENTION_MS = RETENTION_DAYS * DAY_MS

/** Как часто выбрасывать устаревшее: на старте и потом раз в полдня. */
export const PURGE_INTERVAL_MS = 12 * HOUR_MS

/**
 * Больше файл история не хранит: это сборка, дамп или данные, а не то, что правят руками и
 * агентом. Пять мегабайт с запасом вмещают pnpm-lock.yaml крупного монорепозитория.
 */
export const HISTORY_FILE_MAX_BYTES = 5 * 1024 * 1024

/**
 * Сохранения редактора в течение минуты от первого - одна версия: автосохранение пишет файл
 * на каждой паузе в наборе, и без склейки история состояла бы из версий через букву.
 */
export const EDIT_MERGE_MS = MINUTE_MS

/** Сколько живёт намерение IDE (сохранение, возврат версии, правка ссылок) - до события диска. */
export const INTENT_MS = 10 * SECOND_MS

/**
 * Инструмент правки агента идёт - его путь помечен, но не дольше этого: оборванный разговор
 * не пометит чужую правку через час.
 */
export const AGENT_RUNNING_MAX_MS = 10 * MINUTE_MS

/** После конца правки агента событие диска ещё может прийти: слежение копит пачку. */
export const AGENT_GRACE_MS = 10 * SECOND_MS

/** Сколько файлов читать разом при сверке с диском. */
export const READ_BATCH = 64

/** Сколько ключей спрашивать у git одним вызовом. */
export const GIT_BATCH = 512

/** Пауза между полными сверками подряд: pnpm install переполняет слежение каждую секунду. */
export const RESCAN_GAP_MS = 3 * SECOND_MS

/**
 * Папка, которая появилась целиком (перенесли в проект), читается сама; больше файлов в ней -
 * полная сверка проекта.
 */
export const NEW_FOLDER_MAX_FILES = 2_000

/** Больше событий список истории не отдаёт: смена ветки даёт тысячи, листать их некому. */
export const LIST_LIMIT = 500

/** Первая полная сверка проекта - не на старте IDE: окно и провайдеры важнее. */
export const FIRST_SCAN_DELAY_MS = 5 * SECOND_MS

/** Свежее содержимое уборка не трогает: сверка сохраняет его раньше ссылок на него. */
export const KEEP_GRACE_MS = HOUR_MS

/** Сколько байт читать разом при сверке: пачка файлов по 5 МБ не должна держать сотни МБ. */
export const READ_BYTES_BUDGET = 32 * 1024 * 1024

/**
 * Первая сверка копирует к себе только текст, которого нет в git, и не больше этого на
 * проект: папка без git с документами и картинками не должна переехать в базу целиком.
 * Двоичное и то, что не влезло, история знает по ключу, а «до» у его первой правки - нет.
 */
export const BASELINE_COPY_BUDGET = 256 * 1024 * 1024

/**
 * Возврат версии поверх файла, который история не хранит (вырос больше предела), сначала
 * копирует его к себе - но не больше этого: дальше возврат отказывает, а не затирает.
 */
export const RESTORE_KEEP_MAX_BYTES = 64 * 1024 * 1024
