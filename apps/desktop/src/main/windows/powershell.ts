/**
 * Строка для PowerShell в одинарных кавычках: внутри ничего не раскрывается. Кавычку внутри
 * удваивают - и обычную, и типографские (U+2018-U+201B): PowerShell закрывает строку любой из
 * них, и путь с такой буквой иначе разорвал бы строку и стал кодом.
 */
export const psQuote = (value: string): string => `'${value.replace(/['‘-‛]/g, '$&$&')}'`
