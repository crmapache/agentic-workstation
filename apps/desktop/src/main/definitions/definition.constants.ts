/**
 * Сколько процесс определений живёт без вопросов. Он держит компилятор TypeScript и разобранные
 * файлы (около 100 МБ), а нужен, только пока человек ходит по коду с ⌘: простоял - завершается,
 * следующее наведение поднимет его заново (ADR 0061).
 */
export const DEFINITION_IDLE_MS = 5 * 60_000

/** Нет exit за этот срок - интерфейс показывает ошибку, ссылка на процесс остаётся у IDE. */
export const DEFINITION_STOP_MS = 5_000

/**
 * Пауза между мягкой остановкой и SIGKILL. Процессу нечего сохранять (компилятор и кеши), так
 * что долго ждать незачем; не вышел - добиваем, иначе память так и осталась бы занята.
 */
export const DEFINITION_KILL_GRACE_MS = 1_000

/** Зависший компилятор не должен навсегда держать вопрос и весь текст файла в памяти. */
export const DEFINITION_REQUEST_MS = 30_000

/**
 * Текст длиннее этого (в знаках) не разбирается: такой файл - сгенерированный или данные, по
 * нему не ходят, а разбор занял бы секунды.
 */
export const DEFINITION_MAX_TEXT = 3_000_000

/** Сколько текстов открытых файлов помнит процесс: переключение вкладок не шлёт текст заново. */
export const DEFINITION_DOCUMENTS = 8

/** Сколько файлов с диска (куда ведут импорты) процесс держит разобранными. */
export const DEFINITION_SOURCES = 48

/**
 * Сколько шагов по реэкспортам («export { a } from», «export * from») делает поиск имени:
 * цепочка длиннее - почти наверняка петля, дальше не идём и открываем последний модуль.
 */
export const DEFINITION_CHASE_DEPTH = 16
