/**
 * Единицы времени в миллисекундах - одни на все процессы: главный считает по ним статистику,
 * расписание и сроки, окно - часы хода, лимиты и графики. Свои копии по файлам расходились бы
 * записью («60_000», «24 * 60 * 60 * 1000»), а читать их приходилось бы каждый раз заново.
 */

export const SECOND_MS = 1000

export const MINUTE_MS = 60 * SECOND_MS

export const HOUR_MS = 60 * MINUTE_MS

/** Ровно 24 часа. Местные сутки при переводе часов бывают 23 и 25 - их прибавляют календарём. */
export const DAY_MS = 24 * HOUR_MS
