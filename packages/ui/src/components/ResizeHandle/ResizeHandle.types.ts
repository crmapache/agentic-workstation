/** start и end - боковые края (тянут ширину), top и bottom - верх и низ (тянут высоту). */
export type ResizeHandleEdge = 'start' | 'end' | 'top' | 'bottom'

export type ResizeHandleProps = {
  /** У какого края родителя стоит ручка. Родитель должен быть position: relative. */
  edge: ResizeHandleEdge
  /**
   * Ручка в зазоре между листами окна (панели, терминал под панелью): встаёт посередине
   * зазора, а черта не заходит на скругления углов листов. Без него - на самом крае, по
   * разделительной линии внутри листа (код и просмотр Markdown).
   */
  inGap?: boolean | undefined
  /** Подпись для скринридера: что именно меняет размер. */
  label: string
  /**
   * Сдвиг указателя с прошлого вызова, в пикселях: по горизонтали у боковых краёв, по
   * вертикали у верха и низа (вниз - плюс).
   */
  onResize: (delta: number) => void
}
