/**
 * Сколько весит одно сообщение телефона - одно число на обе стороны. Телефон по нему решает,
 * влезут ли фото, IDE - принимает ли собранное из частей, схема команд - потолок картинок. Три
 * разных числа уже расходились: схема пускала 18 МБ фото, а части собирали меньше 4.
 */

/** Сообщение целиком (JSON в UTF-8, как оно собирается из частей) - не тяжелее этого. */
export const MAX_MESSAGE_BYTES = 4 * 1024 * 1024

/** Сколько фото в одном сообщении. */
export const MAX_IMAGES = 6

/** Текст сообщения в знаках. */
export const MAX_TEXT_CHARS = 100_000

/**
 * Все фото сообщения вместе (base64): остальное - место под текст и конверт команды. Жёсткая
 * проверка всё равно по MAX_MESSAGE_BYTES от готового JSON.
 */
export const MAX_IMAGES_CHARS = MAX_MESSAGE_BYTES - 512 * 1024
